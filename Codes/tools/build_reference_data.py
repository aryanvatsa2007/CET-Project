"""Convert the NIST WebBook tables saved in Data/reference/raw_nist into labelled
CSV files, checking each row for transcription errors, and derive the tabulated
input files used by the table scenarios.

Usage:  python Codes/tools/build_reference_data.py   (from the project folder)
"""
import glob
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
RAW = os.path.join(ROOT, "Data", "reference", "raw_nist")
REF = os.path.join(ROOT, "Data", "reference")
TAB = os.path.join(ROOT, "Data", "inputs", "tables")

COLS = ["T [K]", "P [MPa]", "rho [mol/L]", "V [L/mol]", "U [kJ/mol]",
        "H [kJ/mol]", "S [J/(mol*K)]", "Cv [J/(mol*K)]", "Cp [J/(mol*K)]",
        "w [m/s]", "muJT [K/MPa]", "phase"]
CITE = ("Lemmon, E. W.; Bell, I. H.; Huber, M. L.; McLinden, M. O. Thermophysical "
        "Properties of Fluid Systems. In NIST Chemistry WebBook, NIST Standard "
        "Reference Database Number 69; https://doi.org/10.18434/T4D303")


def parse(path):
    """Rows of 11 floats + phase; the two transport columns are dropped if present."""
    head, rows = [], []
    with open(path) as fh:
        for line in fh:
            if line.startswith("#"):
                head.append(line[1:].strip())
                continue
            tok = line.split()
            if not tok:
                continue
            nums, phase = [float(x) for x in tok[:11]], tok[-1]
            T, P, rho, V, U, H = nums[:6]
            # integrity: the printed columns must agree with each other
            if abs(rho * V - 1.0) > 2e-4:
                sys.exit(f"{path}: rho*V != 1 in row {line!r}")
            if abs(H - U - P * V) > 2.5e-3:
                sys.exit(f"{path}: H != U + PV in row {line!r}")
            rows.append(nums + [phase])
    return head, rows


def write(path, title, heads, rows, cols=COLS):
    with open(path, "w") as fh:
        fh.write(f"# {title}\n")
        fh.write(f"# source: {CITE}\n")
        for h in heads:
            fh.write(f"# {h}\n")
        fh.write("# enthalpy and entropy use the NIST default reference state; "
                 "only differences are comparable with the engine\n")
        fh.write(",".join(cols) + "\n")
        for r in rows:
            fh.write(",".join(f"{x:.10g}" if isinstance(x, float) else x for x in r) + "\n")
    print(f"wrote {os.path.relpath(path, ROOT)} ({len(rows)} rows)")


def main():
    os.makedirs(TAB, exist_ok=True)
    iso, heads = [], []
    files = sorted(glob.glob(os.path.join(RAW, "co2_isobar_*MPa.txt")),
                   key=lambda p: float(os.path.basename(p)[11:-7]))
    for f in files:
        h, rows = parse(f)
        heads.append(h[0])
        iso += rows
    write(os.path.join(REF, "nist_co2_isobars_310-400K_0.1-20MPa.csv"),
          "Carbon dioxide, reference values on nine isobars (Span-Wagner equation of state)",
          ["retrieved 2026-11-15 from the fluid.cgi pages listed in raw_nist/"], iso)
    h, rows = parse(os.path.join(RAW, "co2_saturation.txt"))
    write(os.path.join(REF, "nist_co2_saturation_220-300K.csv"),
          "Carbon dioxide, saturated liquid and vapour reference values", h, rows)
    h, rows = parse(os.path.join(RAW, "n2_isotherm_300K.txt"))
    write(os.path.join(REF, "nist_n2_isotherm_300K_1-31MPa.csv"),
          "Nitrogen, reference values on the 300 K isotherm (Span et al. equation of state)",
          h, rows)
    # tabulated P-V-T input: the CO2 isobars as a (T, P, V) grid
    path = os.path.join(TAB, "co2_pvt_table_nist.csv")
    with open(path, "w") as fh:
        fh.write("# INPUT table: molar volume of carbon dioxide on a 19 x 9 (T, P) grid\n")
        fh.write(f"# source: {CITE}; derived from Data/reference/"
                 "nist_co2_isobars_310-400K_0.1-20MPa.csv\n")
        fh.write("T [K],P [MPa],V [L/mol]\n")
        for r in iso:
            fh.write(f"{r[0]:.10g},{r[1]:.10g},{r[3]:.10g}\n")
    print(f"wrote {os.path.relpath(path, ROOT)} ({len(iso)} rows)")
    # tabulated ideal-gas Cp input: the Shomate correlation sampled every 10 K
    sys.path.insert(0, os.path.join(ROOT, "Codes"))
    from thermocalculus.eos import get_fluid
    cp0 = get_fluid("CO2").cp0
    path = os.path.join(TAB, "co2_cp0_table.csv")
    with open(path, "w") as fh:
        fh.write("# INPUT table: ideal-gas isobaric heat capacity of carbon dioxide\n")
        fh.write("# generated by sampling the NIST WebBook Shomate correlation "
                 "(Chase 1998) every 10 K; used to exercise tabulated Cp0 input\n")
        fh.write("T [K],Cp0 [J/(mol*K)]\n")
        for T in range(300, 501, 10):
            fh.write(f"{T},{cp0.cp(float(T)):.6f}\n")
    print(f"wrote {os.path.relpath(path, ROOT)} (21 rows)")


if __name__ == "__main__":
    main()
